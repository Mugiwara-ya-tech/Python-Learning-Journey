# A logical operation takes several boolean inputs and produce only 1 boolean output.

''' First one is the AND operation
        True AND True = True
        True AND False = False
        False AND True = False
        False AND False = False'''

# The "AND" operation result in a True value only when all the inputs are True at the same time.
# To memorize this remember this " True AND True = True, Every other combination = False".

''' Second one is the OR operation
        True OR True = True
        True OR False = True
        False OR True = True
        False OR False = False'''

# The "OR" operation result in a True value if at least one of the input is True.